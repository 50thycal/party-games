import assert from 'node:assert/strict';
import 'fake-indexeddb/auto';
import { createRequire } from 'node:module';
import path from 'node:path';
const require=createRequire(import.meta.url),out=process.argv[2];
const {beginAudit,saveAuditPair,loadAudit,loadAuditExample}=require(path.join(out,'src/games/subway/auditStorage.js'));
const {newAudit}=require(path.join(out,'src/games/subway/cardAudit.js'));
const a=newAudit({trials:1,seed:1});await beginAudit(a,null);
const pair={task:{cardId:'gentle',count:2,trial:0},seat:1,attempts:1};
const example={schema:1,seed:123};
await saveAuditPair(a.storageId,0,pair,[{key:'gentle-targeted-miss',record:example}]);
assert.deepEqual((await loadAudit()).summary.pairs,[pair]);
assert.deepEqual(await loadAuditExample('gentle-targeted-miss',a.storageId),example);
await assert.rejects(saveAuditPair(a.storageId,0,pair,[]));
await assert.rejects(saveAuditPair('wrong',1,pair,[]));
const b=newAudit({trials:1,seed:2});
await assert.rejects(beginAudit(b,null));
assert.equal((await loadAudit()).summary.storageId,a.storageId);
await beginAudit(b,a.storageId);
await saveAuditPair(b.storageId,0,pair,[{key:'gentle-targeted-miss',record:{...example,seed:456}}]);
await assert.rejects(loadAuditExample('gentle-targeted-miss',a.storageId));
await assert.rejects(saveAuditPair(a.storageId,1,pair,[]));
await assert.rejects(beginAudit(newAudit({trials:1,seed:3}),a.storageId));
assert.equal((await loadAudit()).summary.storageId,b.storageId);
assert.equal((await loadAuditExample('gentle-targeted-miss',b.storageId)).seed,456);
console.log('Audit checkpoints: resume, append CAS, stale replacement and stale replay rejection passed.');
