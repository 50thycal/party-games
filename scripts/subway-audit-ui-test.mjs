import assert from 'node:assert/strict';
import 'fake-indexeddb/auto';
import { readFileSync } from 'node:fs';
import Module, { createRequire } from 'node:module';
import path from 'node:path';
import React from 'react';
import { create, act } from 'react-test-renderer';
import ts from 'typescript';
const require=createRequire(import.meta.url),out=process.argv[2];
// Execute the real component/hooks against controlled worker + IndexedDB adapters.
// Production build separately validates the actual import.meta worker bundling.
const filename=path.join(out,'src/games/subway/CardAuditPanel.js');
const compiled=ts.transpileModule(readFileSync('src/games/subway/CardAuditPanel.tsx','utf8').replace('import.meta.url',JSON.stringify('file:///audit')),{compilerOptions:{module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX,target:ts.ScriptTarget.ES2022,esModuleInterop:true}}).outputText;
const m=new Module(filename);m.filename=filename;m.paths=Module._nodeModulePaths(path.dirname(filename));m._compile(compiled,filename);
const {CardAuditPanel}=m.exports;
const {loadAudit}=require(path.join(out,'src/games/subway/auditStorage.js'));
const instances=[];
globalThis.Worker=class {constructor(){this.sent=[];this.terminated=false;instances.push(this);}postMessage(v){this.sent.push(v);}terminate(){this.terminated=true;}};
globalThis.window={confirm:()=>true};
const flush=async()=>{await act(async()=>{for(let i=0;i<20;i++)await new Promise(setImmediate);});};
let view;await act(async()=>{view=create(React.createElement(CardAuditPanel,{onReplay:()=>{}}));});await flush();
const button=text=>view.root.findAllByType('button').find(b=>b.children.join('')===text);
assert.equal(button('Run Full Card Audit').props.disabled,false);
await act(async()=>view.root.findByProps({'aria-label':'Audit trials'}).props.onChange({target:{value:'1'}}));
await act(async()=>button('Run Full Card Audit').props.onClick());await flush();
const first=instances.at(-1);assert.equal(first.sent.length,1);
await act(async()=>button('Stop after current pair').props.onClick());
const task=first.sent[0].task;
const outcome={met:false,points:0,score:0,cash:0,debt:0,complete:0,crews:0,tolls:0,reason:'test adapter'};
await act(async()=>first.onmessage({data:{pair:{task,seat:1,attempts:1,normal:outcome,targeted:outcome},records:[]}}));await flush();
assert.equal(first.terminated,true);assert.equal((await loadAudit()).summary.pairs.length,1);
assert.ok(button('Copy compact report'));assert.ok(button('Resume saved audit'));
await act(async()=>button('Resume saved audit').props.onClick());
const second=instances.at(-1);assert.deepEqual(second.sent[0].task,{...task,count:3});
await act(async()=>view.unmount());assert.equal(second.terminated,true);
await act(async()=>{view=create(React.createElement(CardAuditPanel,{onReplay:()=>{}}));});await flush();
assert.ok(button('Resume saved audit'));
await act(async()=>button('Resume saved audit').props.onClick());
const third=instances.at(-1);assert.deepEqual(third.sent[0].task,{...task,count:3});
await act(async()=>third.onerror({message:'worker test error'}));
assert.equal(third.terminated,true);assert.equal((await loadAudit()).summary.pairs.length,1);
assert.ok(view.root.findByProps({role:'alert'}).children.join('').includes('worker test error'));
await act(async()=>view.unmount());
console.log('Audit UI adapters: full-run start, stop boundary, resume cursor, remount recovery, worker error and cleanup passed. Not a browser/physical-device test.');
