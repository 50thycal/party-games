import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),React=require('react'),{act,create}=require('react-test-renderer');
const {PlayerPads}=require('/tmp/subway-test/src/games/subway/PlayerStatus.js');
const {subwayGame}=require('/tmp/subway-test/src/games/subway/config.js');
const {testRoom}=require('/tmp/subway-test/src/games/subway/playtest.js');
const game=subwayGame.initialState(testRoom(2).players);
const a=game.playerOrder[0],b=game.playerOrder[1];
const event={seq:1,actorId:a,reversed:false,payments:[{from:a,to:b,amount:1,reason:'Station access'},{from:'bank',to:a,amount:3,reason:'Line completed'}]};
let view;
const originalSetTimeout=globalThis.setTimeout,originalClearTimeout=globalThis.clearTimeout;
const timers=new Map();let timerId=0;
globalThis.setTimeout=(fn,ms,...args)=>{if(ms!==3200)return originalSetTimeout(fn,ms,...args);const id=++timerId;timers.set(id,fn);return id;};
globalThis.clearTimeout=id=>{if(timers.has(id))timers.delete(id);else originalClearTimeout(id);};
act(()=>{view=create(React.createElement(PlayerPads,{game,roomKey:'one'}));});
const updated={...game,moneyEvents:[event]};
act(()=>view.update(React.createElement(PlayerPads,{game:updated,roomKey:'one'})));
let status=view.root.findByProps({role:'status'}).children.join('');assert.match(status,/pays/);assert.match(status,/\+\$3M/);
act(()=>view.update(React.createElement(PlayerPads,{game:structuredClone(updated),roomKey:'one'})));
assert.equal(view.root.findByProps({role:'status'}).children.join(''),status,'same poll does not add another event');
act(()=>{const next=timers.values().next().value;next();});
assert.equal(view.root.findByProps({role:'status'}).children.join(''),'Company lines and cash','repeated poll did not queue a duplicate');
act(()=>view.unmount());
act(()=>{view=create(React.createElement(PlayerPads,{game:updated,roomKey:'one'}));});
assert.equal(view.root.findByProps({role:'status'}).children.join(''),'Company lines and cash','remount never replays payment');
act(()=>view.update(React.createElement(PlayerPads,{game:{...game,moneyEvents:[event,{...event,seq:2,reversed:true}]},roomKey:'one'})));
status=view.root.findByProps({role:'status'}).children.join('');assert.match(status,/Undo/);assert.match(status,/−\$3M/);assert.doesNotMatch(status,/\+\$3M/);
act(()=>view.update(React.createElement(PlayerPads,{game:updated,roomKey:'different-room'})));
assert.equal(view.root.findByProps({role:'status'}).children.join(''),'Company lines and cash','new room clears pending animations');
act(()=>view.unmount());
console.log('Player panels: payment/reversal text, repeated polls, remount and room isolation passed.');

globalThis.setTimeout=originalSetTimeout;globalThis.clearTimeout=originalClearTimeout;
